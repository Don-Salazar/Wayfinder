// dump-seeds: optional local development seeds for /wf dump (never committed,
// never shipped in a release).
//
// Reads item IDs from the research CSVs "quest-rewards" and "dungeon-loot"
// and spell IDs from "spell-ids" and "class-abilities" (docs/research/csv,
// git-ignored private research), and writes dist/Wayfinder/Modules/DumpSeeds.lua,
// which sets addon.WF.dumpSeeds = { items = {...}, spells = {...} }. It then
// lists that file in dist/Wayfinder/Wayfinder.toc right after Modules/Core.lua.
// /wf dump uses the seeds only to ask the client about extra IDs; every value
// it records still comes from the client.
//
//   npm run build:addon && npm run dump:seeds
//
// Writes only inside dist/Wayfinder. With no docs/research/csv (as in CI) it
// prints why and does nothing (exit 0). Exit 1 when dist/Wayfinder has not
// been built.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsv } from "../lib/csv.ts";

const REPO_ROOT = resolve(fileURLToPath(new URL("../..", import.meta.url)));
export const RESEARCH_CSV = "docs/research/csv";
export const DIST = "dist/Wayfinder";
export const SEEDS_FILE = "Modules/DumpSeeds.lua";
export const TOC_FILE = "Wayfinder.toc";
export const TOC_ANCHOR = "Modules/Core.lua";

/** Which CSV (without .csv) feeds which seed list, and the ID column header. */
export const SOURCES: readonly { tab: string; kind: "items" | "spells"; column: RegExp }[] = [
  { tab: "quest-rewards", kind: "items", column: /^item id$/i },
  { tab: "dungeon-loot", kind: "items", column: /^item id$/i },
  { tab: "spell-ids", kind: "spells", column: /^spell id$/i },
  { tab: "class-abilities", kind: "spells", column: /^spell ids\b/i },
];

// IDs larger than this are not plausible client IDs (guards against stray numbers).
const MAX_ID = 99_999_999;

/**
 * Numeric IDs from the first column whose header matches `column`. A cell may
 * hold several IDs ("5211, 6798, 8983"); every whole-number token is taken.
 * Rows without a numeric ID are skipped. Returns [] if no column matches.
 */
export function extractIds(rows: string[][], column: RegExp): number[] {
  const header = rows[0];
  if (!header) return [];
  const col = header.findIndex((h) => column.test(h.trim()));
  if (col < 0) return [];
  const out: number[] = [];
  for (const row of rows.slice(1)) {
    const cell = row[col] ?? "";
    for (const token of cell.split(/[,;/\s]+/)) {
      if (!/^\d+$/.test(token)) continue;
      const id = Number(token);
      if (id > 0 && id <= MAX_ID) out.push(id);
    }
  }
  return out;
}

export interface Seeds {
  items: number[];
  spells: number[];
  /** tab -> number of IDs read from it. */
  counts: Record<string, number>;
  /** Tabs that were absent or had no ID column. */
  skipped: string[];
}

/** Read every source CSV in csvDir; unique IDs, ascending. */
export function buildSeeds(csvDir: string): Seeds {
  const sets = { items: new Set<number>(), spells: new Set<number>() };
  const counts: Record<string, number> = {};
  const skipped: string[] = [];
  for (const source of SOURCES) {
    const file = join(csvDir, `${source.tab}.csv`);
    if (!existsSync(file)) {
      skipped.push(`${source.tab} (file missing)`);
      continue;
    }
    const rows = parseCsv(readFileSync(file, "utf8"));
    if (!rows[0]?.some((h) => source.column.test(h.trim()))) {
      skipped.push(`${source.tab} (no column matching ${source.column})`);
      continue;
    }
    const ids = extractIds(rows, source.column);
    counts[source.tab] = ids.length;
    for (const id of ids) sets[source.kind].add(id);
  }
  const sorted = (s: Set<number>) => [...s].sort((a, b) => a - b);
  return { items: sorted(sets.items), spells: sorted(sets.spells), counts, skipped };
}

function luaList(ids: readonly number[], indent: string): string[] {
  const lines: string[] = [];
  for (let i = 0; i < ids.length; i += 12) lines.push(indent + ids.slice(i, i + 12).join(", ") + ",");
  return lines;
}

/** The DumpSeeds.lua text. */
export function renderSeedsLua(seeds: Pick<Seeds, "items" | "spells" | "counts">, date: string): string {
  const sources = Object.entries(seeds.counts)
    .map(([tab, n]) => `${tab} ${n}`)
    .join(", ");
  return [
    "-- Modules/DumpSeeds.lua",
    "-- local development seeds; single-source research; not shipped",
    `-- Generated by tools/dump-seeds on ${date} from ${RESEARCH_CSV} (${sources || "no IDs"}).`,
    "-- Only tells /wf dump which extra item and spell IDs to ask the client about;",
    "-- every value the dump records comes from the client. Lives in dist/ only.",
    "",
    "local _, addon = ...",
    "if not addon.WF then return end",
    "",
    "addon.WF.dumpSeeds = {",
    "    items = {",
    ...luaList(seeds.items, "        "),
    "    },",
    "    spells = {",
    ...luaList(seeds.spells, "        "),
    "    },",
    "}",
    "",
  ].join("\n");
}

/**
 * Add `line` to TOC text right after the line `anchor` (unchanged if `line`
 * is already listed). Throws if the anchor is missing. Keeps CRLF if used.
 */
export function insertTocLine(toc: string, line: string, anchor: string): string {
  const eol = toc.includes("\r\n") ? "\r\n" : "\n";
  const lines = toc.split(/\r?\n/);
  const norm = (s: string) => s.trim().replace(/\\/g, "/").toLowerCase();
  if (lines.some((l) => norm(l) === norm(line))) return toc;
  const at = lines.findIndex((l) => norm(l) === norm(anchor));
  if (at < 0) throw new Error(`dump-seeds: ${anchor} is not listed in the TOC`);
  lines.splice(at + 1, 0, line);
  return lines.join(eol);
}

/** Resolve `rel` under `base` and refuse anything that escapes it. */
function inside(base: string, rel: string): string {
  const p = resolve(base, rel);
  const r = relative(base, p);
  if (r === "" || r.startsWith("..") || r.includes(`..${sep}`) || resolve(r) === r) {
    throw new Error(`dump-seeds: refusing to write ${p} (outside ${base})`);
  }
  return p;
}

export interface RunResult {
  status: "written" | "no-research";
  message: string;
  seeds?: Seeds;
}

export function run(root = REPO_ROOT, date = new Date().toISOString().slice(0, 10)): RunResult {
  const csvDir = join(root, RESEARCH_CSV);
  if (!existsSync(csvDir)) {
    return {
      status: "no-research",
      message: `dump-seeds: ${RESEARCH_CSV} not found (the research folder is local only); no seeds written, nothing changed.`,
    };
  }
  const dist = resolve(root, DIST);
  const tocPath = inside(dist, TOC_FILE);
  if (!existsSync(tocPath)) throw new Error(`dump-seeds: ${DIST}/${TOC_FILE} not found; run "npm run build:addon" first.`);
  const seeds = buildSeeds(csvDir);
  const seedsPath = inside(dist, SEEDS_FILE);
  mkdirSync(dirname(seedsPath), { recursive: true });
  writeFileSync(seedsPath, renderSeedsLua(seeds, date), "utf8");
  const toc = readFileSync(tocPath, "utf8");
  const next = insertTocLine(toc, SEEDS_FILE, TOC_ANCHOR);
  if (next !== toc) writeFileSync(tocPath, next, "utf8");
  const skipped = seeds.skipped.length ? `; skipped: ${seeds.skipped.join(", ")}` : "";
  return {
    status: "written",
    seeds,
    message: `dump-seeds: wrote ${DIST}/${SEEDS_FILE} (${seeds.items.length} item IDs, ${seeds.spells.length} spell IDs) and listed it in ${DIST}/${TOC_FILE}${skipped}. Local development only; never ship this build.`,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const r = run();
    console.log(r.message);
    process.exitCode = 0;
  } catch (e) {
    console.error((e as Error).message);
    process.exitCode = 1;
  }
}
